// Independent workflows accept manual dispatch or dispatch from the trusted label router.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { root } from './lib.mjs';
const check = process.argv.includes('--check');
const expr = value => '${{ ' + value + ' }}';
const pins = {
  checkout: 'actions/checkout@11d5960a326750d5838078e36cf38b85af677262',
  upload: 'actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02',
  download: 'actions/download-artifact@d3f86a106a0bac45b974a628896c90dbdf5c8093',
  node: 'actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020',
};
const checkout = `      - uses: ${pins.checkout}
        with:
          ref: ${expr('github.sha')}
          persist-credentials: false`;
const artifactFiles = ['result.json', 'environment.json', 'review.json', 'mcp.jsonl', 'checks.json', 'smoke.png'];
for (const reviewer of ['claude', 'copilot', 'opencode']) {
  const settings = JSON.parse(await readFile(resolve(root, 'reviewers', reviewer, 'config.json'), 'utf8'));
  if (reviewer === 'claude' && !/^[a-z0-9.-]+$/.test(settings.model)) throw new Error('Invalid Claude model ID.');
  const secret = { claude: 'CLAUDE_CODE_OAUTH_TOKEN', copilot: 'COPILOT_GITHUB_TOKEN', opencode: 'OPENCODE_GO_API_KEY' }[reviewer];
  const agentStep = reviewer === 'claude' ? `      - name: Claude Code Action (subscription only)
        id: agent
        uses: anthropics/claude-code-action@4d75e5f390ee76b2e09c1980ecc99ff3a2e088c8 # v1
        with:
          claude_code_oauth_token: ${expr('secrets.CLAUDE_CODE_OAUTH_TOKEN')}
          github_token: ${expr('github.token')}
          path_to_claude_code_executable: /opt/review-demo/image/agents/node_modules/.bin/claude
          path_to_bun_executable: /opt/review-demo/image/agents/node_modules/.bin/bun
          allowed_bots: 'github-actions'
          track_progress: 'false'
          use_sticky_comment: 'false'
          show_full_output: 'false'
          use_commit_signing: 'false'
          prompt: ${expr('steps.prompt.outputs.text')}
          claude_args: >-
            --model ${settings.model} --effort ${settings.effort} --max-turns 12 --permission-mode default --tools ""
            --strict-mcp-config --mcp-config /tmp/review-run/mcp.json
            --allowedTools mcp__project__review_context,mcp__project__run_checks,mcp__project__submit_review,mcp__serena__list_dir
        env:
          CLAUDE_CODE_DISABLE_AUTO_MEMORY: '1'
          DISABLE_AUTOUPDATER: '1'` : `      - name: ${reviewer === 'copilot' ? 'Copilot CLI (personal subscription)' : 'OpenCode CLI (Go subscription)'}
        id: agent
        env:
          ${secret}: ${expr('secrets.' + secret)}
        run: node /opt/review-demo/reviewers/${reviewer}/run.mjs /tmp/review-run`;
  const text = `# Review a selected fixture PR in the main image, validate tool evidence, then publish.
# Generated by scripts/generate-workflows.mjs; edit generator and regenerate.
name: Review / ${reviewer}
run-name: "${reviewer} / ${settings.model}${settings.effort ? ' / ' + settings.effort : ''} / PR #${expr('inputs.pr_number')}"
on:
  workflow_dispatch:
    inputs:
      pr_number:
        description: 'Open same-repository PR changing only demo/pricing.json'
        required: true
        type: string
      comment_id:
        description: Internal PR follow-up comment ID
        type: string
        required: false
      label_run_id:
        description: 'Internal label-router run ID; leave empty for manual runs'
        required: false
        type: string
permissions:
  contents: read
concurrency:
  group: review-${reviewer}-${expr('inputs.pr_number')}
  cancel-in-progress: false
jobs:
  prepare:
    if: github.ref == 'refs/heads/main'
    runs-on: ubuntu-latest
    timeout-minutes: 15
    permissions:
      contents: read
      pull-requests: read
      packages: read
      actions: read
    outputs:
      image: ${expr('steps.image.outputs.image')}
    steps:
${checkout}
      - uses: ${pins.node}
        with:
          node-version: '22'
      - name: Verify actor and snapshot PR data
        env:
          GH_TOKEN: ${expr('github.token')}
          PR_NUMBER: ${expr('inputs.pr_number')}
          COMMENT_ID: ${expr('inputs.comment_id')}
          ROUTER_RUN_ID: ${expr('inputs.label_run_id')}
          REVIEWER: ${reviewer}
        run: node scripts/prepare-pr.mjs
      - uses: docker/login-action@c94ce9fb468520275223c153574b00df6fe4bcc9 # v3
        with:
          registry: ghcr.io
          username: ${expr('github.actor')}
          password: ${expr('github.token')}
      - name: Resolve main image to verified digest
        id: image
        run: node scripts/resolve-image.mjs
      - uses: ${pins.upload}
        with:
          name: ${reviewer}-input-${expr('github.run_id')}-${expr('github.run_attempt')}
          path: artifacts/input/*.json
          retention-days: 7
          if-no-files-found: error
  review:
    needs: prepare
    runs-on: ubuntu-latest
    timeout-minutes: 18
    permissions:
      contents: read
      pull-requests: read
      packages: read
    container:
      image: ${expr('needs.prepare.outputs.image')}
      credentials:
        username: ${expr('github.actor')}
        password: ${expr('github.token')}
    defaults:
      run:
        shell: bash
    env:
      REVIEW_IMAGE: ${expr('needs.prepare.outputs.image')}
    steps:
${checkout}
      - uses: ${pins.download}
        with:
          name: ${reviewer}-input-${expr('github.run_id')}-${expr('github.run_attempt')}
          path: /tmp/review-input
      - name: Prepare trusted MCP configuration and fixture
        run: node /opt/review-demo/scripts/prepare-run.mjs ${reviewer} /tmp/review-input/input.json /tmp/review-run
      - name: Check required credential
        env:
          DEMO_CREDENTIAL: ${expr('secrets.' + secret)}
        run: |
          if [ -z "$DEMO_CREDENTIAL" ]; then
            echo 'BLOCKED: AUTH_MISSING — configure ${secret}'
            exit 1
          fi
${reviewer === 'claude' ? `      - name: Load trusted review prompt
        id: prompt
        run: |
          echo 'text<<REVIEW_PROMPT_END' >> "$GITHUB_OUTPUT"
          cat /tmp/review-run/prompt.txt >> "$GITHUB_OUTPUT"
          echo 'REVIEW_PROMPT_END' >> "$GITHUB_OUTPUT"
` : ''}${agentStep}
      - name: Validate evidence (never claims PASS before publication)
        if: always()
        env:
          AGENT_OUTCOME: ${expr('steps.agent.outcome')}
        run: node /opt/review-demo/scripts/finalize.mjs /tmp/review-run
      - name: Upload only reviewed evidence files
        if: always()
        uses: ${pins.upload}
        with:
          name: ${reviewer}-evidence-${expr('github.run_id')}-${expr('github.run_attempt')}
          path: |
${artifactFiles.map(name => '            /tmp/review-run/' + name).join('\n')}
          if-no-files-found: error
          retention-days: 14
  publish:
    needs: review
    runs-on: ubuntu-latest
    timeout-minutes: 5
    permissions:
      contents: read
      pull-requests: write
    steps:
${checkout}
      - uses: ${pins.node}
        with:
          node-version: '22'
      - run: npm ci --ignore-scripts
      - uses: ${pins.download}
        with:
          name: ${reviewer}-evidence-${expr('github.run_id')}-${expr('github.run_attempt')}
          path: artifacts/publish
      - name: Revalidate commit and publish independent PR review
        env:
          GH_TOKEN: ${expr('github.token')}
          PR_NUMBER: ${expr('inputs.pr_number')}
          REVIEWER: ${reviewer}
        run: node scripts/publish.mjs artifacts/publish
      - uses: ${pins.upload}
        if: always()
        with:
          name: ${reviewer}-publication-${expr('github.run_id')}-${expr('github.run_attempt')}
          path: artifacts/publish/published.json
          retention-days: 30
          if-no-files-found: error
`;
  const path = resolve(root, '.github/workflows', `review-${reviewer}.yml`);
  if (check) {
    if (await readFile(path, 'utf8') !== text) throw new Error(`Workflow drift: ${path}`);
  } else {
    await mkdir(resolve(root, '.github/workflows'), { recursive: true });
    await writeFile(path, text);
  }
}
